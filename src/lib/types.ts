export type Platform = "tiktok" | "youtube" | "instagram" | "other";
export type MetricSnapshot = {
  observedAt: string;
  views: number | null;
  likes: number | null;
  comments: number | null;
  shares: number | null;
  source: string;
};
export type FrameEvidence = { seconds: number; image: string };
export type Video = {
  id: string;
  url: string;
  platform: Platform;
  title: string;
  creator: string;
  publishedAt: string | null;
  duration: number | null;
  followers: number | null;
  thumbnail?: string;
  mediaUrl?: string;
  transcript?: string;
  transcriptSource?: string;
  transcriptSegments?: {start: number; end: number; text: string}[];
  description?: string;
  hashtags?: string[];
  onScreenText?: string;
  visualNotes?: string;
  frames?: FrameEvidence[];
  snapshots: MetricSnapshot[];
  source: string;
  fetchedAt: string;
};
